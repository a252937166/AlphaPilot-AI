class ProductionAuthorityError(RuntimeError):
    """Natural, fail-closed authority validation failure."""


def _require(condition: Any, message: str) -> None:
    if not condition:
        raise ProductionAuthorityError(message)


def _sha(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def _canonical(value: Any) -> bytes:
    return (
        json.dumps(
            value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False
        )
        + "\n"
    ).encode("utf-8")


def _read_bytes(path: Path) -> bytes:
    path = Path(path)
    _require(path.is_absolute(), f"absolute path required: {path}")
    # Refuse symlink ancestors as well as a symlink leaf.
    for component in (path, *path.parents):
        _require(not component.is_symlink(), f"symlink evidence/source: {component}")
    try:
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
        try:
            before = os.fstat(fd)
            _require(stat.S_ISREG(before.st_mode), f"not a regular file: {path}")
            with os.fdopen(fd, "rb", closefd=False) as stream:
                value = stream.read()
            after = os.fstat(fd)
            _require(
                (
                    before.st_dev,
                    before.st_ino,
                    before.st_size,
                    before.st_mtime_ns,
                    before.st_ctime_ns,
                )
                == (
                    after.st_dev,
                    after.st_ino,
                    after.st_size,
                    after.st_mtime_ns,
                    after.st_ctime_ns,
                ),
                f"file changed during read: {path}",
            )
            return value
        finally:
            os.close(fd)
    except OSError as error:
        raise ProductionAuthorityError(f"cannot read {path}: {error}") from error


def _decode(value: bytes) -> Any:
    def pairs(items: list[tuple[str, Any]]) -> dict[str, Any]:
        result: dict[str, Any] = {}
        for key, item in items:
            _require(key not in result, f"duplicate JSON key: {key}")
            result[key] = item
        return result

    def constant(value: str) -> Any:
        raise ProductionAuthorityError(f"non-finite JSON number: {value}")

    def floating(value: str) -> float:
        result = float(value)
        _require(math.isfinite(result), "non-finite JSON exponent")
        return result

    try:
        return json.loads(
            value.decode("utf-8"),
            object_pairs_hook=pairs,
            parse_constant=constant,
            parse_float=floating,
        )
    except (ValueError, UnicodeError) as error:
        raise ProductionAuthorityError(f"invalid JSON: {error}") from error


def _read_json(path: Path) -> dict[str, Any]:
    result = _decode(_read_bytes(path))
    _require(type(result) is dict, f"expected JSON object: {path}")
    return result


def _relative(value: str) -> str:
    _require(type(value) is str and bool(value), "empty/non-string relative path")
    parsed = PurePosixPath(value)
    _require(
        not parsed.is_absolute()
        and ".." not in parsed.parts
        and parsed.as_posix() == value
        and "\\" not in value,
        f"non-canonical repository path: {value}",
    )
    return value


def _oid(value: str) -> str:
    _require(type(value) is str and re.fullmatch("[0-9a-f]{40}", value), "invalid full commit OID")
    return value


def _git(root: Path, *arguments: str) -> bytes:
    # This is an internal read-only allowlist, not a general command gateway.
    _require(
        bool(arguments)
        and arguments[0]
        in {
            "rev-parse",
            "rev-list",
            "show",
            "cat-file",
            "ls-tree",
            "ls-files",
            "diff",
            "diff-tree",
            "log",
            "for-each-ref",
            "symbolic-ref",
        },
        "unregistered Git operation",
    )
    environment = {
        "PATH": "/usr/bin:/bin:/usr/sbin:/sbin",
        "LANG": "C",
        "LC_ALL": "C",
        "GIT_CONFIG_GLOBAL": "/dev/null",
        "GIT_CONFIG_SYSTEM": "/dev/null",
        "GIT_CONFIG_NOSYSTEM": "1",
        "GIT_OPTIONAL_LOCKS": "0",
        "GIT_NO_REPLACE_OBJECTS": "1",
        "GIT_NO_LAZY_FETCH": "1",
        "GIT_TERMINAL_PROMPT": "0",
        "GIT_ALLOW_PROTOCOL": "",
    }
    result = subprocess.run(
        [
            "/usr/bin/git",
            "-c",
            "core.fsmonitor=false",
            "-c",
            "core.hooksPath=/dev/null",
            "-c",
            "gc.auto=0",
            "-c",
            "core.quotePath=false",
            "-C",
            str(root),
            *arguments,
        ],
        stdin=subprocess.DEVNULL,
        capture_output=True,
        env=environment,
        check=False,
    )
    _require(
        result.returncode == 0,
        f"read-only git {arguments!r}: rc={result.returncode}: "
        + result.stderr.decode("utf-8", errors="replace"),
    )
    return result.stdout


def _repository(root: Path) -> Path:
    root = Path(root)
    _require(root.is_absolute() and root == root.resolve(), "non-canonical root")
    _require(
        (root / ".git").is_dir() and not (root / ".git").is_symlink(),
        "standalone repository required",
    )
    for name in (
        "shallow",
        "info/grafts",
        "objects/info/alternates",
        "objects/info/http-alternates",
    ):
        _require(
            not os.path.lexists(root / ".git" / name),
            f"unsupported Git history indirection: {name}",
        )
    _require(not _git(root, "for-each-ref", "refs/replace").strip(), "replacement refs prohibited")
    _require(
        _git(root, "rev-parse", "--show-toplevel").decode().strip() == str(root),
        "Git root mismatch",
    )
    return root


def _ancestor(root: Path, older: str, newer: str) -> None:
    older, newer = _oid(older), _oid(newer)
    _require(
        _git(root, "cat-file", "-t", older).strip() == b"commit"
        and _git(root, "cat-file", "-t", newer).strip() == b"commit",
        "lineage object is not a commit",
    )
    _require(
        older.encode() in _git(root, "rev-list", newer).splitlines(),
        f"commit {older} not in ancestry of {newer}",
    )


def _refs(root: Path) -> bytes:
    return _git(
        root, "for-each-ref", "--format=%(refname)%00%(objectname)%00%(objecttype)%00%(symref)%00"
    )


def _file_ref(
    root: Path,
    ref: dict[str, Any],
    expected_path: str | None = None,
    expected_sha: str | None = None,
) -> tuple[Path, bytes]:
    _require(type(ref) is dict and {"path", "sha256"} <= ref.keys(), "invalid file reference")
    name = ref["path"]
    _require(type(name) is str, "non-string reference path")
    if expected_path is not None:
        _require(name == expected_path, "reference path drifted")
    path = Path(name) if Path(name).is_absolute() else root / _relative(name)
    value = _read_bytes(path)
    _require(_sha(value) == ref["sha256"], f"reference SHA mismatch: {path}")
    if expected_sha is not None:
        _require(_sha(value) == expected_sha, f"registered SHA mismatch: {path}")
    if "bytes" in ref:
        _require(
            type(ref["bytes"]) is int and len(value) == ref["bytes"],
            f"reference byte count mismatch: {path}",
        )
    return path, value


def _creation(root: Path, path: str, expected_commit: str | None = None) -> str:
    path = _relative(path)
    touches = (
        _git(root, "log", "--all", "--full-history", "--format=%H", "--", path)
        .decode()
        .splitlines()
    )
    _require(len(touches) == 1, f"authority path needs one unique creation: {path}")
    commit = _oid(touches[0])
    if expected_commit is not None:
        _require(commit == _oid(expected_commit), f"creating commit drifted: {path}")
    parents = _git(root, "rev-list", "--parents", "-n", "1", commit).decode().split()
    _require(len(parents) == 2, f"authority creation is not single-parent: {path}")
    changed = (
        _git(root, "diff-tree", "--no-commit-id", "--name-status", "-r", "--no-renames", commit)
        .decode()
        .splitlines()
    )
    _require(changed == ["A\t" + path], f"authority creation is not unique-A: {path}")
    head = _git(root, "rev-parse", "HEAD").decode().strip()
    _ancestor(root, commit, head)
    _require(
        _git(root, "show", f"{commit}:{path}") == _read_bytes(root / path),
        f"authority worktree/creating blob mismatch: {path}",
    )
    _require(
        _git(root, "show", f"HEAD:{path}") == _read_bytes(root / path),
        f"authority HEAD/worktree mismatch: {path}",
    )
    _require(
        _git(root, "show", f":{path}") == _read_bytes(root / path),
        f"authority index/worktree mismatch: {path}",
    )
    return commit


def _authority_ref(
    root: Path,
    ref: dict[str, Any],
    expected_path: str | None = None,
    expected_sha: str | None = None,
) -> tuple[dict[str, Any], str]:
    path, value = _file_ref(root, ref, expected_path, expected_sha)
    _require(path.is_relative_to(root), "authority must be repository-relative")
    commit = _creation(root, path.relative_to(root).as_posix(), ref["creating_commit"])
    parsed = _decode(value)
    _require(type(parsed) is dict, "authority must be an object")
    return parsed, commit


def _tracked_tree(root: Path, commit: str) -> dict[str, tuple[str, str]]:
    result = {}
    for record in _git(root, "ls-tree", "-rz", "--full-tree", _oid(commit)).split(b"\0"):
        if not record:
            continue
        header, raw_path = record.split(b"\t", 1)
        mode, kind, oid = header.decode().split()
        name = _relative(raw_path.decode("utf-8"))
        result[name] = (mode, oid)
        _require(kind != "commit", "Git submodules are not a registered source surface")
    return result


def registered_source_closure(root: Path, implementation_commit: str) -> list[dict[str, Any]]:
    """Inventory every tracked Python/config file, including dynamic imports.

    This deliberately conservative closure avoids an AST-only import graph
    silently omitting function-local imports, wrapper entrypoints or data configs.
    The list comes from Git, never from the supplied manifest.
    """
    root = _repository(root)
    tree = _tracked_tree(root, implementation_commit)
    names = sorted(name for name in tree if name.endswith(".py") or name.startswith("config/"))
    _require(
        {PREPARE_RELATIVE, MODULE_RELATIVE, SCHEMA_RELATIVE} <= set(names),
        "implementation closure lacks required source/schema",
    )
    records = []
    for name in names:
        mode, oid = tree[name]
        _require(mode in {"100644", "100755"}, f"non-regular source: {name}")
        value = _read_bytes(root / name)
        _require(
            _git(root, "cat-file", "blob", oid) == value,
            f"live implementation source drifted: {name}",
        )
        records.append({"path": name, "sha256": _sha(value), "bytes": len(value)})
    return records


def execution_environment() -> dict[str, Any]:
    """Current interpreter/package inventory; no environment installation."""
    executable = Path(sys.executable).resolve()
    packages = sorted(
        (
            {
                "name": re.sub(r"[-_.]+", "-", str(dist.metadata["Name"])).lower(),
                "version": dist.version,
            }
            for dist in importlib.metadata.distributions()
        ),
        key=lambda item: (item["name"], item["version"]),
    )
    _require(
        len({item["name"] for item in packages}) == len(packages),
        "duplicate environment distributions",
    )
    return {
        "interpreter_realpath": str(executable),
        "interpreter_sha256": _sha(_read_bytes(executable)),
        "python_version": sys.version,
        "packages": packages,
        "packages_sha256": _sha(_canonical(packages)),
    }


def _changes(root: Path, commit: str) -> list[dict[str, str]]:
    records = []
    for row in (
        _git(root, "diff", "--name-status", "--no-renames", BASE_COMMIT, _oid(commit))
        .decode()
        .splitlines()
    ):
        status, name = row.split("\t")
        records.append({"status": status, "path": name})
    return sorted(records, key=lambda item: item["path"])


def validate_implementation_binding(
    root: Path,
    implementation_binding: dict[str, Any],
    *,
    reviewed_commit: str | None = None,
) -> dict[str, Any]:
    """Active validator for the actual committed implementation; read-only.

    May inspect an isolated clone. Execution admission additionally validates the
    loaded module origins against that same root; inspection itself grants none.
    """
    _module_integrity()
    root = _repository(root)
    binding = implementation_binding
    _require(
        type(binding) is dict
        and set(binding)
        == {
            "implementation_commit",
            "build_manifest",
            "prepare_exception",
            "source_closure",
            "active_validator",
            "execution_environment",
        },
        "implementation binding fields drifted",
    )
    commit = _oid(binding["implementation_commit"])
    if reviewed_commit is not None:
        _require(commit == reviewed_commit, "reviewed implementation commit mismatch")
    _ancestor(root, BASE_COMMIT, commit)
    _ancestor(root, commit, _git(root, "rev-parse", "HEAD").decode().strip())
    changes = _changes(root, commit)
    _require(
        {x["path"]: x["status"] for x in changes} == _ALLOWED_CHANGES,
        "implementation changed an unregistered surface or lacks a required file",
    )
    for intermediate in _git(root, "rev-list", f"{BASE_COMMIT}..{commit}").decode().splitlines():
        parents = _git(root, "rev-list", "--parents", "-n", "1", intermediate).decode().split()
        _require(len(parents) == 2, "implementation history must remain single-parent")
        for row in (
            _git(
                root,
                "diff-tree",
                "--no-commit-id",
                "--name-status",
                "-r",
                "--no-renames",
                intermediate,
            )
            .decode()
            .splitlines()
        ):
            status, name = row.split("\t")
            _require(
                name in _ALLOWED_CHANGES and status in {"A", "M"},
                "intermediate implementation commit touched a forbidden file",
            )
    _require(
        not _git(root, "diff", "--no-ext-diff", "--name-only", "HEAD").strip(),
        "tracked worktree or index drift",
    )
    _require(
        not _git(root, "diff", "--cached", "--no-ext-diff", "--name-only", "HEAD").strip(),
        "index drift",
    )
    expected_prepare = {
        "path": PREPARE_RELATIVE,
        "base_sha256": PREPARE_BASE_SHA,
        "target_sha256": PREPARE_TARGET_SHA,
        "patch_sha256": PATCH_SHA,
    }
    _require(binding["prepare_exception"] == expected_prepare, "prepare exception drifted")
    _require(
        _sha(_git(root, "show", f"{BASE_COMMIT}:{PREPARE_RELATIVE}")) == PREPARE_BASE_SHA,
        "prepare base bytes drifted",
    )
    _require(
        _sha(_read_bytes(root / PREPARE_RELATIVE)) == PREPARE_TARGET_SHA,
        "prepare target is not the exact reviewed patch",
    )
    closure = registered_source_closure(root, commit)
    _require(binding["source_closure"] == closure, "source closure mismatch/omission")
    closure_map = {item["path"]: item for item in closure}
    _require(
        binding["active_validator"]
        == {
            "path": MODULE_RELATIVE,
            "sha256": closure_map[MODULE_RELATIVE]["sha256"],
            "entrypoint": "validate_implementation_binding",
            "implementation_commit": commit,
        },
        "active validator binding drifted",
    )
    _, raw_manifest = _file_ref(root, binding["build_manifest"])
    manifest = _decode(raw_manifest)
    _require(
        manifest
        == {
            "schema_version": "p4.2a-successor-production-integration-v1-build-manifest",
            "implementation_commit": commit,
            "source_closure": closure,
            "changed_paths": changes,
        },
        "build manifest does not describe actual implementation",
    )
    environment = execution_environment()
    _require(
        binding["execution_environment"] == environment,
        "current interpreter or package set differs from release binding",
    )
    return {
        "implementation_commit": commit,
        "source_closure_sha256": _sha(_canonical(closure)),
        "execution_environment_sha256": _sha(_canonical(environment)),
        "changed_paths": changes,
        "active_validator": binding["active_validator"],
    }


def has_registered_release_candidate(root: Path) -> bool:
    return os.path.lexists(Path(root) / RELEASE_RELATIVE)


def _timestamp(value: str) -> dt.datetime:
    try:
        parsed = dt.datetime.fromisoformat(value.replace("Z", "+00:00"))
        _require(parsed.tzinfo is not None, "timestamp lacks timezone")
        return parsed
    except (ValueError, TypeError, AttributeError) as error:
        raise ProductionAuthorityError("invalid timestamp") from error


def _external_source(root: Path, value: dict[str, Any]) -> dict[str, Any]:
    source = _read_bytes(Path(value["source_path"]))
    _require(
        len(source) == value["source_bytes"] and _sha(source) == value["source_sha256"],
        "owner original source byte/hash mismatch",
    )
    _require(source == value["verbatim_text"].encode("utf-8"), "owner original wording was changed")
    relay_raw = _read_bytes(Path(value["relay_path"]))
    _require(_sha(relay_raw) == value["relay_sha256"], "owner relay SHA mismatch")
    relay = _decode(relay_raw)
    _require(type(relay) is dict, "owner relay is not an object")
    for key in (
        "source_path",
        "source_sha256",
        "source_bytes",
        "verbatim_text",
        "observed_at_utc",
        "delivery_channel",
    ):
        _require(relay.get(key) == value[key], f"owner relay binding mismatch: {key}")
    _require(relay.get("owner_identity") == "ouyang", "owner relay identity mismatch")
    _require(
        _timestamp(value["observed_at_utc"]) <= dt.datetime.now(dt.UTC), "future owner observation"
    )
    return relay


def _registered_checks(
    root: Path, checks: list[dict[str, Any]], policy: dict[str, Any], implementation_commit: str
) -> None:
    # Keep pyexpat helpers out of the frozen v2.1 bootstrap origin census.
    from xml.etree import ElementTree

    _require(
        type(checks) is list
        and len(checks) == len(_CHECK_IDS)
        and {item["check_id"] for item in checks} == set(_CHECK_IDS),
        "missing or duplicate registered checks",
    )
    argv = policy["registered_tests"][0]["proposed_argv"]
    for item in checks:
        _require(
            item["rc"] == 0 and type(item["rc"]) is int and item["status"] == "PASS",
            "registered check did not pass naturally",
        )
        _, command_raw = _file_ref(root, item["command_ref"])
        command = _decode(command_raw)
        _require(
            type(command) is dict
            and command.get("argv") == argv
            and command.get("implementation_commit") == implementation_commit
            and command.get("rc") == 0
            and type(command.get("rc")) is int,
            "registered check argv/commit/result mismatch",
        )
        _require(
            type(command.get("environment")) is dict
            and command["environment"].get("PYTHONDONTWRITEBYTECODE") == "1",
            "registered command environment missing",
        )
        options = command["environment"].get("PYTEST_ADDOPTS", "")
        _require(
            not any(
                token in options
                for token in ("--deselect", "--ignore", "--collect-only", "-k ", "-m ")
            ),
            "registered test command selected a partial suite",
        )
        _require(
            _timestamp(command["ended_at_utc"]) >= _timestamp(command["started_at_utc"]),
            "registered command time order",
        )
        for stream in ("stdout", "stderr"):
            _, raw = _file_ref(root, command[stream])
            _require(_sha(raw) == item[stream + "_sha256"], "registered output SHA mismatch")
        _, report_raw = _file_ref(root, command["junit_xml"])
        _require(
            b"<!DOCTYPE" not in report_raw and b"<!ENTITY" not in report_raw,
            "JUnit entities are forbidden",
        )
        try:
            report = ElementTree.fromstring(report_raw)
        except ElementTree.ParseError as error:
            raise ProductionAuthorityError("invalid registered JUnit report") from error
        cases = list(report.iter("testcase"))
        suites = list(report.iter("testsuite"))
        _require(
            cases
            and suites
            and all(
                not list(case)
                or all(child.tag in {"system-out", "system-err", "properties"} for child in case)
                for case in cases
            ),
            "registered tests include failure/error/skip",
        )
        _require(
            sum(int(suite.attrib["tests"]) for suite in suites) == len(cases)
            and all(
                int(suite.attrib.get(field, "0")) == 0
                for suite in suites
                for field in ("failures", "errors", "skipped")
            ),
            "JUnit counts are inconsistent or not all passed",
        )
        classnames = {case.attrib["classname"] for case in cases}
        required_classes = {
            "tests.test_p4_2a_successor_production_authority",
            "tests.test_p4_2a_successor_preparation_integration",
        }
        _require(classnames == required_classes, "JUnit does not cover both registered files")
        identities = {case.attrib["classname"] + "::" + case.attrib["name"] for case in cases}
        _require(len(identities) == len(cases), "duplicate JUnit test identities")
        coverage = command["check_coverage"]
        _require(
            set(coverage) == set(_CHECK_IDS)
            and all(
                type(nodes) is list and nodes and set(nodes) <= identities
                for nodes in coverage.values()
            ),
            "registered check coverage lacks actual passing test identities",
        )
        evidence = item["evidence_refs"]
        _require(type(evidence) is list and bool(evidence), "missing registered test evidence")
        for ref in evidence:
            _file_ref(root, ref)


def _review(
    root: Path, receipt: dict[str, Any], policy: dict[str, Any], implementation: dict[str, Any]
) -> tuple[dict[str, Any], str]:
    review, commit = _authority_ref(
        root, receipt["independent_implementation_review_ref"], REVIEW_RELATIVE
    )
    required = {
        "schema_version",
        "verdict",
        "created_at_utc",
        "reviewer",
        "preregistration_ref",
        "owner_exception_ref",
        "implementation_binding",
        "registered_checks",
        "changed_paths",
        "historical_h0_separation",
    }
    _require(set(review) == required, "independent review fields drifted")
    _require(
        review["schema_version"]
        == "p4.2a-successor-production-integration-v1-independent-implementation-review",
        "independent review schema mismatch",
    )
    _require(
        review["verdict"] == "PASS_SUCCESSOR_PRODUCTION_INTEGRATION_V1_IMPLEMENTATION_REVIEW",
        "independent implementation review not PASS",
    )
    _require(
        review["reviewer"] == receipt["reviewer"]
        and review["reviewer"]["independent_of_operator"] is True,
        "reviewer declaration mismatch or not independent",
    )
    _require(
        review["preregistration_ref"] == receipt["lineage"]["preregistration"]
        and review["owner_exception_ref"] == receipt["lineage"]["owner_exception"],
        "independent review registration mismatch",
    )
    _require(
        review["implementation_binding"] == receipt["production_implementation_binding"]
        and review["changed_paths"] == implementation["changed_paths"]
        and review["historical_h0_separation"] is True,
        "independent implementation/source binding mismatch",
    )
    _require(
        review["registered_checks"] == receipt["registered_checks"],
        "independent review did not bind registered test outputs",
    )
    _ancestor(root, implementation["implementation_commit"], commit)
    _require(
        _git(root, "rev-parse", commit + "^").decode().strip()
        == implementation["implementation_commit"],
        "review must directly follow implementation",
    )
    _require(
        _timestamp(review["reviewer"]["observed_at_utc"])
        <= _timestamp(review["created_at_utc"])
        <= _timestamp(receipt["created_at_utc"]),
        "independent review time order",
    )
    for ref in review["reviewer"]["evidence_refs"]:
        _file_ref(root, ref)
    _registered_checks(
        root, receipt["registered_checks"], policy, implementation["implementation_commit"]
    )
    return review, commit


@dataclass(frozen=True, slots=True, weakref_slot=True)
class ProductionPreparationAuthorization:
    project_root: Path
    receipt_path: Path
    receipt_sha256: str
    receipt_creating_commit: str
    preregistration_commit: str
    implementation_commit: str
    validated_stage: str | None = None
    reviewed_repository_head: str = ""
    owner_exception_commit: str = ""
    historical_h0_sha256: str = ""
    source_closure_sha256: str = ""
    execution_environment_sha256: str = ""
    evidence_json: bytes = b"{}"
    _seal: object | None = field(default=None, repr=False, compare=False)

    def __reduce__(self) -> Any:
        raise ProductionAuthorityError("production authority cannot be serialized")


def _facts(value: ProductionPreparationAuthorization) -> bytes:
    return _canonical(
        {
            item.name: str(getattr(value, item.name))
            if isinstance(getattr(value, item.name), Path)
            else getattr(value, item.name).decode("utf-8")
            if item.name == "evidence_json"
            else getattr(value, item.name)
            for item in dataclasses.fields(value)
            if item.name != "_seal"
        }
    )


def _issued(value: Any) -> ProductionPreparationAuthorization:
    _require(type(value) is ProductionPreparationAuthorization, "unissued authority type")
    registration = _ISSUED.get(id(value))
    _require(
        registration is not None
        and registration[0]() is value
        and registration[1] == _facts(value),
        "unissued or mutated authority facts",
    )
    return value


def _module_integrity() -> None:
    for name, (original, code) in _FUNCTION_IDENTITIES.items():
        observed = globals().get(name)
        _require(
            observed is original and getattr(observed, "__code__", None) is code,
            f"authority callable was injected: {name}",
        )


def _validate_loaded_callables(module: Any, path: Path, payload: bytes) -> None:
    """Compare repository function code with compilation of its committed bytes.

    Compiling does not execute the module. Decorator wrappers are followed to
    their original callable; closure code remains present in the compiled tree.
    """
    compiled = compile(payload, str(path), "exec", dont_inherit=True, optimize=sys.flags.optimize)
    syntax = ast.parse(payload, filename=str(path))
    declared = {
        node.name
        for node in syntax.body
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
    }
    owned = set(declared)
    for node in syntax.body:
        if (
            isinstance(node, (ast.Assign, ast.AnnAssign))
            and isinstance(node.value, ast.Call)
            and isinstance(node.value.func, ast.Name)
            and node.value.func.id in declared
        ):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            owned.update(
                target.id
                for target in ast.walk(ast.Tuple(elts=targets))
                if isinstance(target, ast.Name)
            )
    expected: set[types.CodeType] = set()

    def visit(code: types.CodeType) -> None:
        expected.add(code)
        for value in code.co_consts:
            if isinstance(value, types.CodeType):
                visit(value)

    visit(compiled)
    for name, function in vars(module).items():
        if name in owned and (callable(function) or name in declared):
            _require(
                getattr(function, "__module__", None) == module.__name__,
                f"loaded repository callable owner differs: {module.__name__}.{name}",
            )
        if not isinstance(function, types.FunctionType) or function.__module__ != module.__name__:
            continue
        seen: set[int] = set()
        while hasattr(function, "__wrapped__"):
            _require(id(function) not in seen, "cyclic callable wrapper")
            seen.add(id(function))
            function = function.__wrapped__
        _require(
            isinstance(function, types.FunctionType)
            and (name not in declared or function.__code__.co_name == name)
            and any(
                function.__code__ == registered
                and function.__code__.co_filename == registered.co_filename
                and function.__code__.co_firstlineno == registered.co_firstlineno
                and function.__code__.co_qualname == registered.co_qualname
                for registered in expected
            ),
            f"loaded repository callable code differs: {module.__name__}.{name}",
        )


def _loaded_origins(root: Path, closure: list[dict[str, Any]]) -> None:
    _require(
        root / MODULE_RELATIVE == _ORIGIN and Path(__file__).resolve() == _ORIGIN,
        "non-canonical authority module",
    )
    _module_integrity()
    source_map = {item["path"]: item for item in closure}
    stdlib = Path(sysconfig.get_path("stdlib")).resolve()
    site_roots = {Path(sysconfig.get_path(key)).resolve() for key in ("purelib", "platlib")}
    for name, module in tuple(sys.modules.items()):
        origin = getattr(module, "__file__", None)
        repository_namespace = (
            name == "scripts"
            or name.startswith("scripts.")
            or name == "alphapilot"
            or name.startswith("alphapilot.")
        )
        if not origin or str(origin).startswith("<"):
            if repository_namespace:
                spec = getattr(module, "__spec__", None)
                locations = getattr(spec, "submodule_search_locations", None)
                expected = root / ("scripts" if name == "scripts" else "src/alphapilot")
                _require(
                    name in {"scripts", "alphapilot"}
                    and locations is not None
                    and {Path(value).resolve() for value in locations} == {expected},
                    f"originless repository module: {name}",
                )
            continue
        path = Path(origin).resolve()
        if path.is_relative_to(root) and ".venv" not in path.relative_to(root).parts:
            relative = path.relative_to(root).as_posix()
            _require(relative in source_map, f"unregistered loaded repository module: {name}")
            payload = _read_bytes(path)
            _require(
                _sha(payload) == source_map[relative]["sha256"],
                f"loaded repository source mismatch: {name}",
            )
            _validate_loaded_callables(module, path, payload)
            if (
                name == "scripts"
                or name.startswith("scripts.")
                or name == "alphapilot"
                or name.startswith("alphapilot.")
            ):
                stem = name.replace(".", "/")
                expected = [root / (stem + ".py"), root / stem / "__init__.py"]
                if name.startswith("alphapilot"):
                    expected = [root / "src" / (stem + ".py"), root / "src" / stem / "__init__.py"]
                _require(path in expected, f"repository module alias/shadow: {name}")
        elif (
            name == "scripts"
            or name.startswith("scripts.")
            or name == "alphapilot"
            or name.startswith("alphapilot.")
        ):
            raise ProductionAuthorityError(f"repository module outside canonical root: {name}")
        else:
            _require(
                path.is_relative_to(stdlib)
                or any(path.is_relative_to(site) for site in site_roots),
                f"loaded module outside registered runtime roots: {name}",
            )


def _validate_policy_scope(receipt: dict[str, Any], policy: dict[str, Any]) -> None:
    _require(
        receipt["authorized_stages"] == list(ALLOWED_STAGES),
        "production release does not grant exactly five preparation stages",
    )
    _require(policy["authorized_stages"] == [], "preregistration is not design-only")
    for key in ("still_gated", "runtime_start_policy", "locks", "failure_policy"):
        _require(receipt[key] == policy[key], f"registered preparation policy drifted: {key}")


def _validate_local_schema_refs(value: Any) -> None:
    if type(value) is dict:
        for key, item in value.items():
            if key in {"$ref", "$dynamicRef", "$recursiveRef"}:
                _require(type(item) is str and item.startswith("#"), "non-local schema reference")
            _validate_local_schema_refs(item)
    elif type(value) is list:
        for item in value:
            _validate_local_schema_refs(item)


def _validate_registered_budget(root: Path, receipt: dict[str, Any]) -> dict[str, Any]:
    """Check the confirmed plan before artifacts/DB access; not a billing meter.

    The original 4048-item frame is a conservative call bound before eligibility
    materialization. Frozen per-call cost is an estimate, never a guaranteed live
    provider charge. Any new price/billing limit needs the independent review.
    """
    relative = "docs/phase4/reports/P4.2a-v2-heldout-preregistration-20260810.json"
    raw = _read_bytes(root / relative)
    _require(
        _sha(raw) == "ccecbf5ca7b48b16e445318b8c94a08927432f92c7e8c12f8ab40f2916578705",
        "frozen heldout plan drifted",
    )
    plan = _decode(raw)
    cost_ref = plan["authorities"]["cost_correction_and_p4_2b_backlog"]
    _, cost_raw = _file_ref(root, cost_ref)
    cost = _decode(cost_raw)
    calls = plan["source_frame"]["expected_raw_candidate_count"]
    per_call = cost["part_1_cost_correction"]["measured_reality"]["cost_per_call"]["qwen3.6-plus"]
    estimated_cost = calls * per_call
    facts = receipt["external_cost_confirmation"]["budget_facts"]
    limits = receipt["execution_limits"]
    _require(
        facts["estimated_model_calls"] == calls and limits["maximum_model_calls"] >= calls,
        "confirmed calls do not cover the registered raw frame",
    )
    _require(
        facts["estimated_cost_cny"] >= estimated_cost
        and limits["maximum_total_cost_cny"] >= facts["estimated_cost_cny"],
        "confirmed budget is below the registered cost estimate",
    )
    bases = facts["basis_refs"]
    _require(
        any(ref["path"] == relative and ref["sha256"] == _sha(raw) for ref in bases)
        and any(
            ref["path"] == cost_ref["path"] and ref["sha256"] == cost_ref["sha256"] for ref in bases
        ),
        "budget lacks the frozen frame/cost basis",
    )
    return {
        "model_calls_upper_bound": calls,
        "historical_cost_estimate_cny": estimated_cost,
        "live_provider_charge_guaranteed": False,
        "billing_meter_performed": False,
    }


def validate_preparation_authorization(
    root: Path,
    *,
    stage: str | None,
) -> ProductionPreparationAuthorization:
    _require(stage is None or stage in ALLOWED_STAGES, f"unregistered stage: {stage!r}")
    root = _repository(Path(root))
    _require(
        root / MODULE_RELATIVE == _ORIGIN, "production authority requires canonical module root"
    )
    _require(
        has_registered_release_candidate(root), "BLOCKED_PENDING_SUCCESSOR_PRODUCTION_OWNER_RELEASE"
    )
    before_refs = _refs(root)
    raw = _read_bytes(root / RELEASE_RELATIVE)
    receipt = _decode(raw)
    schema = _read_json(root / SCHEMA_RELATIVE)
    _validate_local_schema_refs(schema)
    Draft202012Validator.check_schema(schema)
    errors = sorted(
        Draft202012Validator(schema, format_checker=FormatChecker()).iter_errors(receipt),
        key=lambda error: str(error.absolute_path),
    )
    _require(
        not errors,
        "production release schema: "
        + ("; ".join(error.message for error in errors[:8]) if errors else ""),
    )
    _require(raw == _canonical(receipt), "production release must use canonical JSON bytes")
    created = _timestamp(receipt["created_at_utc"])
    shanghai = _timestamp(receipt["created_at_shanghai"])
    _require(
        created.utcoffset() == dt.timedelta(0)
        and shanghai.utcoffset() == dt.timedelta(hours=8)
        and created == shanghai
        and created <= dt.datetime.now(dt.UTC),
        "production release creation timestamps mismatch/future",
    )
    observed = _timestamp(receipt["owner_decision_source"]["observed_at_utc"])
    _require(
        observed <= created
        and receipt["authorization_id"].endswith(
            observed.astimezone(ZoneInfo("Asia/Shanghai")).strftime("%Y%m%d")
        ),
        "authorization ID must use the actual owner issuance day",
    )
    lineage = receipt["lineage"]
    policy, prereg_commit = _authority_ref(
        root, lineage["preregistration"], PREREG_RELATIVE, PREREG_SHA
    )
    _owner, exception_commit = _authority_ref(
        root, lineage["owner_exception"], EXCEPTION_RELATIVE, EXCEPTION_SHA
    )
    _require(
        prereg_commit == PREREG_COMMIT and exception_commit == BASE_COMMIT,
        "registration commit pins drifted",
    )
    _require(
        receipt["historical_anchor_h0"] == policy["historical_anchor_h0"],
        "historical H0 epoch/source distinction drifted",
    )
    _validate_policy_scope(receipt, policy)
    _file_ref(
        root,
        lineage["release_schema"],
        SCHEMA_RELATIVE,
        _sha(_canonical(schema))
        if _read_bytes(root / SCHEMA_RELATIVE) == _canonical(schema)
        else _sha(_read_bytes(root / SCHEMA_RELATIVE)),
    )
    implementation = validate_implementation_binding(
        root, receipt["production_implementation_binding"]
    )
    _loaded_origins(root, receipt["production_implementation_binding"]["source_closure"])
    _review(root, receipt, policy, implementation)
    release_commit = _creation(root, RELEASE_RELATIVE)
    parent = _git(root, "rev-parse", release_commit + "^").decode().strip()
    _require(parent == receipt["reviewed_repository_head"], "release reviewed-head/parent mismatch")
    _require(
        parent == receipt["independent_implementation_review_ref"]["creating_commit"],
        "release must directly follow the independent review",
    )
    _ancestor(root, receipt["independent_implementation_review_ref"]["creating_commit"], parent)
    head = _git(root, "rev-parse", "HEAD").decode().strip()
    _require(head == release_commit, "unreviewed commits after production release")
    for ref in ("refs/heads/main", "refs/remotes/origin/main"):
        _require(
            _git(root, "rev-parse", ref).decode().strip() == head,
            "production release is not registered on main/origin-main",
        )
    _require(
        _git(root, "symbolic-ref", "HEAD").decode().strip() == "refs/heads/main",
        "real preparation requires canonical main checkout",
    )
    owner_relay = _external_source(root, receipt["owner_decision_source"])
    _require(
        owner_relay.get("implementation_commit") == implementation["implementation_commit"]
        and owner_relay.get("independent_review_sha256")
        == receipt["independent_implementation_review_ref"]["sha256"]
        and owner_relay.get("authorization_id") == receipt["authorization_id"]
        and owner_relay.get("verdict") == receipt["verdict"],
        "owner source does not bind this implementation/review/release decision",
    )
    cost = receipt["external_cost_confirmation"]
    cost_relay = _external_source(root, cost["owner_source"])
    _require(
        cost_relay.get("budget_facts") == cost["budget_facts"],
        "owner cost statement does not bind actual budget facts",
    )
    _require(
        _timestamp(cost["owner_source"]["observed_at_utc"]) <= created,
        "cost observation after receipt creation",
    )
    for key in ("maximum_model_calls", "maximum_total_cost_cny", "currency"):
        _require(
            cost["budget_facts"][key] == receipt["execution_limits"][key],
            "owner cost/authorization limit mismatch",
        )
    _require(
        cost["budget_facts"]["estimated_model_calls"] <= cost["budget_facts"]["maximum_model_calls"]
        and cost["budget_facts"]["estimated_cost_cny"]
        <= cost["budget_facts"]["maximum_total_cost_cny"],
        "estimated work exceeds confirmed budget",
    )
    for ref in cost["budget_facts"]["basis_refs"]:
        _file_ref(root, ref)
    registered_budget = _validate_registered_budget(root, receipt)
    _file_ref(root, receipt["supporting_evidence_manifest"])
    historical = _validate_historical_h0(root, policy, receipt)
    _require(_refs(root) == before_refs, "references changed during authority validation")
    evidence = {
        "mode": "successor_production_preparation_only",
        "release_authorization": {
            "path": RELEASE_RELATIVE,
            "sha256": _sha(raw),
            "creating_commit": release_commit,
        },
        "preregistration": lineage["preregistration"],
        "owner_exception": lineage["owner_exception"],
        "implementation_commit": implementation["implementation_commit"],
        "source_closure_sha256": implementation["source_closure_sha256"],
        "execution_environment_sha256": implementation["execution_environment_sha256"],
        "independent_implementation_review": receipt["independent_implementation_review_ref"],
        "historical_h0": historical,
        "authorized_stages": list(ALLOWED_STAGES),
        "still_gated": receipt["still_gated"],
        "locks": receipt["locks"],
        "runtime_start_policy": receipt["runtime_start_policy"],
        "registered_budget": registered_budget,
        "refs_sha256": _sha(before_refs),
    }
    facts = ProductionPreparationAuthorization(
        root,
        root / RELEASE_RELATIVE,
        _sha(raw),
        release_commit,
        prereg_commit,
        implementation["implementation_commit"],
        stage,
        parent,
        exception_commit,
        lineage["h0_evidence_acceptance"]["sha256"],
        implementation["source_closure_sha256"],
        implementation["execution_environment_sha256"],
        _canonical(evidence),
        object(),
    )
    key = id(facts)
    _ISSUED[key] = (weakref.ref(facts, lambda ref: _ISSUED.pop(key, None)), _facts(facts))
    return facts


