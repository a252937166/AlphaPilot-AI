# Historical adapter is defined below; function identities are captured after all
# source definitions. No historical pipeline or consume command is executed.


def _validate_historical_h0(root: Path, policy: dict, receipt: dict) -> dict:
    """Rehash the registered H0 history and its original execution evidence.

    This is a new, read-only historical adapter. It neither calls the former
    consume entry point nor replays a scientific pipeline. The selected epoch 6,
    acceptance-time epoch 9, and current production implementation are distinct.
    Clone file modes are not represented as original publication file modes.
    """
    import json
    import re
    import stat

    def relative(value: str) -> str:
        _require(
            isinstance(value, str)
            and re.fullmatch(r"[A-Za-z0-9._/-]+", value) is not None
            and not value.startswith("/")
            and all(part not in ("", ".", "..") for part in value.split("/")),
            "historical evidence has a noncanonical relative path",
        )
        return value

    def checked_json(raw: bytes):
        def pairs(items):
            result = {}
            for key, value in items:
                _require(key not in result, "duplicate key in historical JSON")
                result[key] = value
            return result

        def constant(value):
            _require(False, "nonfinite value in historical JSON: " + value)

        return json.loads(raw.decode("utf-8"), object_pairs_hook=pairs, parse_constant=constant)

    def tree(directory: Path):
        _require(
            directory.resolve(strict=True) == directory.absolute()
            and stat.S_ISDIR(directory.lstat().st_mode),
            "historical tree root is not a canonical directory",
        )
        before = {}
        identities = {}
        payloads = {}
        for path in [
            directory,
            *sorted(
                directory.rglob("*"),
                key=lambda item: item.relative_to(directory).as_posix().encode("utf-8"),
            ),
        ]:
            name = "." if path == directory else relative(path.relative_to(directory).as_posix())
            metadata = path.lstat()
            before[name] = (
                metadata.st_dev,
                metadata.st_ino,
                metadata.st_mode,
                metadata.st_nlink,
                metadata.st_size,
                metadata.st_mtime_ns,
                metadata.st_ctime_ns,
            )
            if stat.S_ISDIR(metadata.st_mode):
                identities[name] = f"directory:{stat.S_IMODE(metadata.st_mode):04o}"
            else:
                _require(
                    stat.S_ISREG(metadata.st_mode) and metadata.st_nlink == 1,
                    "historical evidence contains a link or special file: " + str(path),
                )
                raw = _read_bytes(path)
                _require(len(raw) == metadata.st_size, "historical evidence size changed")
                payloads[name] = raw
                identities[name] = (
                    f"file:{_sha(raw)}:{stat.S_IMODE(metadata.st_mode):04o}:{metadata.st_nlink}"
                )
        observed = {"."} | {item.relative_to(directory).as_posix() for item in directory.rglob("*")}
        _require(observed == set(before), "historical tree membership changed during read")
        for name, identity in before.items():
            metadata = (directory if name == "." else directory / name).lstat()
            _require(
                identity
                == (
                    metadata.st_dev,
                    metadata.st_ino,
                    metadata.st_mode,
                    metadata.st_nlink,
                    metadata.st_size,
                    metadata.st_mtime_ns,
                    metadata.st_ctime_ns,
                ),
                "historical tree changed during read: " + name,
            )
        return identities, payloads

    def merkle(payloads, leaf_domain, node_domain=b"p4.2a-rehearsal-node-v2.2\0", empty=None):
        if not payloads:
            _require(empty is not None, "historical nonempty Merkle tree is empty")
            return _sha(empty)
        nodes = [
            bytes.fromhex(
                _sha(
                    leaf_domain
                    + relative(name).encode("utf-8")
                    + b"\0"
                    + bytes.fromhex(_sha(payloads[name]))
                )
            )
            for name in sorted(payloads, key=lambda value: value.encode("utf-8"))
        ]
        while len(nodes) > 1:
            next_nodes = []
            for index in range(0, len(nodes), 2):
                left = nodes[index]
                right = nodes[index + 1] if index + 1 < len(nodes) else left
                next_nodes.append(bytes.fromhex(_sha(node_domain + left + right)))
            nodes = next_nodes
        return nodes[0].hex()

